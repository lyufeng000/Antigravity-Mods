let added = 0, changed = 0;
const put = (bucket, k, v) => {
  if (!(k in bucket)) added++; else if (bucket[k] !== v) changed++;
  bucket[k] = v;
};
for (const [k, v] of Object.entries(exact)) put(d.exact, k, v);
for (const [k, v] of Object.entries(patterns)) put(d.patterns, k, v);
d.meta.manualAdditions = [...new Set([...(d.meta.manualAdditions ?? []), ...Object.keys(exact), ...Object.keys(patterns)])];
fs.writeFileSync(file, JSON.stringify(d, null, 2));
